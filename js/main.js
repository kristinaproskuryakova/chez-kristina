const DEFAULT_LANG = "fr";
const LANG_KEY = "chez-kristina-lang";

function getSavedLang() {
  try {
    return localStorage.getItem(LANG_KEY);
  } catch (e) {
    return null;
  }
}

function saveLang(lang) {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch (e) {
    // хранилище недоступно — язык просто не запомнится
  }
}

function setLanguage(lang) {
  const dict = translations[lang] || translations[DEFAULT_LANG];

  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const text = dict[el.dataset.i18n];
    if (text) el.textContent = text;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const text = dict[el.dataset.i18nPlaceholder];
    if (text) el.placeholder = text;
  });

  document.querySelectorAll("[data-i18n-label]").forEach((el) => {
    const text = dict[el.dataset.i18nLabel];
    if (text) el.setAttribute("aria-label", text);
  });

  if (dict["meta.title"]) document.title = dict["meta.title"];

  // Юридические страницы: на английском ведём на privacy-en.html и т. д.
  document.querySelectorAll("[data-legal]").forEach((link) => {
    link.setAttribute("href", `${link.dataset.legal}${lang === "en" ? "-en" : ""}.html`);
  });

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
  });

  saveLang(lang);
  updateToggleLabel();
  // Меню (js/menu.js) перерисовывает описания блюд на новом языке
  document.dispatchEvent(new Event("sitelanguagechange"));
}

document.querySelectorAll(".lang-switch button").forEach((btn) => {
  btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
});

